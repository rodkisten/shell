import {readFile,readdir} from 'node:fs/promises';
import {join} from 'node:path';
const remote='apps/workflow/dist';
const host='apps/federation-host/dist';
const manifest=JSON.parse(await readFile(join(remote,'mf-manifest.json'),'utf8'));
if(!manifest.exposes?.some(e=>e.name==='WorkflowStudio'||e.path==='./WorkflowStudio'||e.name==='./WorkflowStudio')) throw Error('WorkflowStudio missing from manifest');
const files=await readdir(remote,{recursive:true});
if(!files.some(f=>f.endsWith('remoteEntry.js'))) throw Error('remoteEntry.js missing');
await readFile(join(host,'index.html'),'utf8');
console.log('Federation artifact contract verified');
